(ns lupapalvelu.foreman-pdf
  "Tools for generating a PDF document when a foreman is terminated"
  (:require [clojure.java.io :as io]
            [lupapalvelu.application-meta-fields :as meta-fields]
            [lupapalvelu.i18n :as i18n]
            [lupapalvelu.organization :as org]
            [lupapalvelu.pate.pdf-html :as html]
            [lupapalvelu.pdf.html-template :as html-pdf]
            [lupapalvelu.user :as user]
            [sade.date :as date]
            [schema-tools.core :as st]
            [schema.core :as sc])
  (:import [java.io ByteArrayInputStream]))

(defn- header
  [{:keys [organization-name title subtitle now]} loc]
  [:div.header
   [:div.section.header
    [:div.row.pad-after
     [:div.cell.cell--30
      organization-name]
     [:div.cell.cell--40.center
      title]
     [:div.cell.cell--30.right
      [:div.permit subtitle]]]
    [:div.row
     [:div.cell.cell--30]
     [:div.cell.cell--40.center
      now]
     [:div.cell.cell--30.right.page-number
      (loc :pdf.page)
      " " [:span.pageNumber]]]]])

(defn- top-row
  [loc k v]
  [:div.section
   [:div.row {:class [:bold :pad-after]}
    [:div.cell {:class [:cell--30 :bold]}
     (loc k)]
    [:div.cell v]]])

(defn- plain-row
  [loc k v]
  [:div.section
   [:div.row
    [:div.cell {:class [:cell--30]}
     (loc k)]
    [:div.cell v]]])

(defn- body
  [{:keys [permit-id foreman role confirmer reason duration decision-date final-date]} loc]
  (list
    (top-row loc :foreman.termination.document.application-id permit-id)
    (plain-row loc :foreman.termination.document.foreman foreman)
    (plain-row loc :foreman.termination.document.role role)
    (plain-row loc :foreman.termination.document.duration duration)
    (plain-row loc :foreman.termination.document.decision-date decision-date)
    (plain-row loc :foreman.termination.document.final-date final-date)
    (plain-row loc :foreman.termination.document.confirmer confirmer)
    (plain-row loc :foreman.termination.document.reason reason)))

(defn- footer
  []
  [:div.footer])

(defn- with-properties
  "Extract interesting properties from the application"
  [{:keys                                 [loc lang now organization foreman-app-or-doc]
    {{:keys [confirmer
             reason
             started
             ended]} :foremanTermination} :foreman-app-or-doc
    :as                                   args}]
  ;; Read the foreman details from the source document, instead of relying on the
  ;; autogenerated `:foreman` and `:foremanRole` fields in the application root.
  (let [{:keys [foreman foremanRole] :as i} (meta-fields/foreman-index foreman-app-or-doc)
        title                               (loc :foreman.termination.document.title)]
    (assoc args :properties {:title  title
                             :header {:title             title
                                      :organization-name (org/get-organization-name organization lang)
                                      :subtitle          (loc :foreman.termination.document.subtitle)
                                      :now               (date/finnish-date now)}
                             :body   {:permit-id     (:id foreman-app-or-doc)
                                      :foreman       foreman
                                      :role          (loc (str "osapuoli.tyonjohtaja.kuntaRoolikoodi." foremanRole))
                                      :confirmer     (user/full-name confirmer)
                                      :reason        reason
                                      :duration      (format "%s - %s"
                                                             (date/finnish-date started)
                                                             (date/finnish-date ended))
                                      :decision-date (date/finnish-date now)
                                      :final-date    (-> now
                                                         (date/plus :days 14)
                                                         date/finnish-date)}})))

(defn- ->hiccup
  "Turn properties into hiccup"
  [{:keys [properties loc]}]
  {:title    (:title properties)
   :h-header (header (:header properties) loc)
   :h-body   (body (:body properties) loc)
   :h-footer (footer)})

(defn- ->html
  "Turn hiccup fields into html"
  [{:keys [h-header h-body h-footer] :as args}]
  (assoc args
         :header (html/html h-header)
         :body (html/html h-body)
         :footer (html/html h-footer)))

(def ^:private margins {:top    "35mm"
                        :bottom "25mm"
                        :left   "9mm"
                        :right  "9mm"})

(sc/defschema GenerateArgs
  (st/open-schema
    {:lang               sc/Keyword
     :now                sc/Int
     :foreman-app-or-doc sc/Any
     :organization       sc/Any
     :system             sc/Any}))

(sc/defschema GenerateResponse
  (st/optional-keys
    {:ok   sc/Bool
     :text sc/Str
     :pdf-file-stream (sc/pred (fn [bais] (instance? ByteArrayInputStream bais)))}))

(sc/defn generate-termination-document :- GenerateResponse
  [{:keys [lang system] :as args} :- GenerateArgs]
  {:pre [(map? system)]}
  (html-pdf/html->pdf
    system
    (-> args
        (assoc :loc (partial i18n/localize lang))
        with-properties
        ->hiccup
        ->html)
    margins))


